-- =============================================================================
-- ArcGPT — Student Dataset Expansion (idempotent, transactional)
-- =============================================================================
-- Brings the institution to exactly STUDENTS_PER_DEPARTMENT ACTIVE students in
-- every existing department, and generates guardian, CGPA, backlog, residency
-- and randomized attendance data.
--
-- IMPORTANT — the numbers reconcile themselves. There is no hardcoded total.
-- With the current 6 departments and 50 students each the dataset ends at 300
-- students. If a tenth department is ever added it becomes 500, with no edit
-- here. Creating extra departments to reach a round total is deliberately NOT
-- done: the department list is the institution's, not the seed's.
--
-- Sources of truth (deliberate, to avoid conflicting copies):
--   * CGPA lives in `student_academic_summary`. It is NOT copied onto
--     `students`, and the profile view reads it from there.
--   * Active backlogs live in `backlogs`. The count is DERIVED by the view;
--     `student_academic_summary.backlog_count` is kept in sync as a cache only.
--   * Attendance percentage is never stored. It is computed by
--     `student_attendance_percentage` from the attendance records.
--   * Residency lives in `student_residency`. `hostel_allocations` is left
--     untouched so there is exactly one authority for DAY_SCHOLAR/HOSTELLER.
--
-- Reproducibility: setseed() pins the generator, so a re-run on a fresh database
-- produces the same dataset. Attendance is randomized at the individual
-- record level, never per department, so no department bias is introduced.
--
-- All data is synthetic. Names are common Indian given/family names; no real
-- individual's data is generated, and no existing row is deleted except the
-- attendance mark sheets, which are regenerated by design.
-- =============================================================================

