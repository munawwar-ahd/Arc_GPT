CREATE TEMP TABLE seed_config (key TEXT PRIMARY KEY, value TEXT NOT NULL) ON COMMIT DROP;
INSERT INTO seed_config (key, value) VALUES
    ('students_per_department',  '50'),   -- target ACTIVE students per department
    ('day_scholar_percentage',   '65'),   -- must sum to 100 with the next value
    ('hosteller_percentage',     '35'),
    ('random_seed',              '0.424242'),
    -- Trim ACTIVE backlogs above a student's deterministic target so the shape
    -- really is "0 backlogs = majority". This is the only step in the script
    -- that removes rows; it touches synthetic backlog entries only. Set to
    -- 'false' to append-only and never delete.
    ('normalize_backlogs',       'true');

-- Pin the generator so the dataset is reproducible.
SELECT setseed((SELECT value::float8 FROM seed_config WHERE key = 'random_seed'));

DO $$
DECLARE
    d_sum int;
    spd   int;
BEGIN
    SELECT (SELECT value::int FROM pg_temp.seed_config WHERE key = 'students_per_department'),
           (SELECT value::int FROM pg_temp.seed_config WHERE key = 'day_scholar_percentage')
         + (SELECT value::int FROM pg_temp.seed_config WHERE key = 'hosteller_percentage')
      INTO spd, d_sum;
    IF spd < 1 THEN
        RAISE EXCEPTION 'students_per_department must be at least 1';
    END IF;
    IF d_sum <> 100 THEN
        RAISE EXCEPTION 'day_scholar_percentage + hosteller_percentage must equal 100 (got %)', d_sum;
    END IF;
END $$;

