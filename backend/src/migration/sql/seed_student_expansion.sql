FROM (
    SELECT 100.0 * COUNT(*) FILTER (WHERE a.status IN ('PRESENT','OD')) / COUNT(*) AS pct
    FROM public.attendance a
    JOIN public.students s ON s.student_id = a.student_id
    GROUP BY s.department_id
) t;
